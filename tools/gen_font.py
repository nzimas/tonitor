# TONITOR: the screen's fonts, rendered to a C header. Made for low vision: three large sizes only.
#   XL  the layer number      digits (and the notes A..G, #: the root), ~100 px
#   L   the engine            capitals, digits, + - . ! ?, ~46 px
#   M   the sound, messages   the same set, ~34 px
# With assets/fonts/AtkinsonHyperlegible-Bold.ttf (the Braille Institute's typeface for low vision,
# SIL OFL 1.1) the glyphs are anti-aliased from it; without it, from Terminus Bold (SIL OFL 1.1, the
# 8 x 16 bitmap font that SLOOP uses) enlarged by whole pixels -- coarse, but crisp and legible.
# Glyph data: 4-bit alpha, two pixels a byte (high nibble first), rows top to bottom; each glyph's
# bitmap starts PAD pixels left of the pen.
"""tools/gen_font.py OUT.h"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONTS = Path(__file__).resolve().parents[1] / "assets" / "fonts"
TTF = FONTS / "AtkinsonHyperlegible-Bold.ttf"
BDF = FONTS / "ter-u16b.bdf"
PAD = 2
CHARS = " !#%+-./0123456789?ABCDEFGHIJKLMNOPQRSTUVWXYZ"
# name, characters, TTF pixel size, Terminus scale
SIZES = [("XL", "#0123456789ABCDEFG", 136, 9), ("L", CHARS, 60, 4), ("M", CHARS, 46, 3), ("S", CHARS, 35, 2)]


def bdf_glyphs():
    lines = BDF.read_text(errors="replace").splitlines()
    fbb = next(l for l in lines if l.startswith("FONTBOUNDINGBOX")).split()
    cw, ch, fy = int(fbb[1]), int(fbb[2]), int(fbb[4])
    base = ch + fy
    glyphs, i = {}, 0
    while i < len(lines):
        if lines[i].startswith("ENCODING"):
            code = int(lines[i].split()[1])
            j = i
            while not lines[j].startswith("BBX"):
                j += 1
            bw, bh, bx, by = map(int, lines[j].split()[1:5])
            k = j
            while not lines[k].startswith("BITMAP"):
                k += 1
            rows = [int(r, 16) for r in lines[k + 1:k + 1 + bh]]
            nbits = ((bw + 7) // 8) * 8
            cell = [[0] * cw for _ in range(ch)]
            top = base - (by + bh)
            for r, bits in enumerate(rows):
                for c in range(bw):
                    if bits >> (nbits - 1 - c) & 1:
                        x, y = bx + c, top + r
                        if 0 <= x < cw and 0 <= y < ch:
                            cell[y][x] = 15
            glyphs[code] = cell
            i = k + bh
        i += 1
    return cw, ch, glyphs


def render_terminus(chars, scale):
    cw, ch, g = bdf_glyphs()
    # crop the empty rows above the capitals and below the baseline's descent, so the type sits tight
    rows = [y for c in chars if ord(c) in g for y in range(ch) if any(g[ord(c)][y])]
    y0, y1 = min(rows), max(rows) + 1
    out = []
    for c in chars:
        cell = g.get(ord(c), g[ord("?")])
        w = cw * scale + 2 * PAD
        px = []
        for y in range(y0 * scale, y1 * scale):
            row = [0] * PAD + [cell[y // scale][x // scale] for x in range(cw * scale)] + [0] * PAD
            px.append(row)
        out.append((c, cw * scale, w, px))
    return (y1 - y0) * scale, out


def render_ttf(chars, size):
    font = ImageFont.truetype(str(TTF), size)
    # the box from the top of the capitals and digits to the baseline, plus a little for the descent
    top = min(font.getbbox(c)[1] for c in chars if c.strip())
    bot = max(font.getbbox(c)[3] for c in chars if c.strip())
    h = bot - top
    out = []
    for c in chars:
        adv = int(round(font.getlength(c)))
        w = adv + 2 * PAD
        img = Image.new("L", (w, bot + 4), 0)
        ImageDraw.Draw(img).text((PAD, 0), c, font=font, fill=255)
        img = img.crop((0, top, w, bot))
        data = img.tobytes()
        px = [[min(15, (data[y * w + x] + 8) // 17) for x in range(w)] for y in range(h)]
        out.append((c, adv, w, px))
    return h, out


def main(path):
    use_ttf = TTF.exists()
    L = [f"/* generated by tools/gen_font.py from {TTF.name if use_ttf else BDF.name} */", "#pragma once",
         "#include <stdint.h>", f"#define FONT_PAD {PAD}", ""]
    for name, chars, size, scale in SIZES:
        h, glyphs = render_ttf(chars, size) if use_ttf else render_terminus(chars, scale)
        data, offs, advs, bws, codes = [], [], [], [], []
        for c, adv, w, px in glyphs:
            offs.append(len(data))
            for row in px:
                row = row + [0]
                for x in range(0, w, 2):
                    data.append((row[x] << 4) | row[x + 1])
            advs.append(adv)
            bws.append(w)
            codes.append(ord(c))
        L.append(f"static const uint8_t FONT_{name}_DATA[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            L.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        L.append("};")
        L.append(f"static const uint32_t FONT_{name}_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};")
        L.append(f"static const uint8_t FONT_{name}_ADV[{len(advs)}] = {{" + ", ".join(map(str, advs)) + "};")
        L.append(f"static const uint8_t FONT_{name}_BW[{len(bws)}] = {{" + ", ".join(map(str, bws)) + "};")
        L.append(f"static const char FONT_{name}_CHARS[] = \"{chars}\";")
        L.append(f"static const font_t FONT_{name} = {{{h}, {len(chars)}, FONT_{name}_CHARS, FONT_{name}_ADV, "
                 f"FONT_{name}_BW, FONT_{name}_OFF, FONT_{name}_DATA}};")
        L.append("")
        print(f"font {name}: {'ttf' if use_ttf else 'terminus'} h {h}, {len(data)} B")
    Path(path).write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
