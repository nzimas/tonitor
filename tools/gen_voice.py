"""TONITOR's SCREEN READER: tools/voice_words.txt (word TAB ARPAbet) -> voice_dict.h, the words sorted, each its
letters (lower case), a 0, then its phonemes, a byte each (the phoneme in the low 6 bits, the stress in the top
2; firmware/src/voice.c), with their offsets.

    python3 tools/gen_voice.py tools/voice_words.txt build/gen/voice_dict.h
"""
import sys

PH = ("SIL AA AE AH AO AW AY EH ER EY IH IY OW OY UH UW B CH D DH F G HH JH K L M N NG P R S SH "
      "T TH V W Y Z ZH").split()


def load(src):
    words = {}
    for no, ln in enumerate(open(src, encoding="ascii"), 1):
        ln = ln.rstrip("\n")
        if not ln.strip() or ln.startswith("#"):
            continue
        try:
            w, ph = ln.split("\t")
        except ValueError:
            raise SystemExit(f"{src}:{no}: not 'word<TAB>phonemes'")
        w = w.lower()
        if not w.isalpha() or not w.isascii():
            raise SystemExit(f"{src}:{no}: a word is letters only: {w!r}")
        if w in words:
            raise SystemExit(f"{src}:{no}: {w} twice")
        out = []
        for p in ph.split():
            st = int(p[-1]) if p[-1].isdigit() else 0
            base = p.rstrip("012")
            if base not in PH or base == "SIL":
                raise SystemExit(f"{src}:{no}: unknown phoneme {p}")
            out.append(PH.index(base) | (st << 6))
        if not out:
            raise SystemExit(f"{src}:{no}: no phonemes")
        words[w] = out
    return words


def main(src, dst):
    words = load(src)
    blob, offs = [], []
    for w in sorted(words):
        offs.append(len(blob))
        blob += [ord(ch) for ch in w] + [0] + words[w]
    offs.append(len(blob))
    if len(blob) > 65535:
        raise SystemExit("gen_voice: the dictionary outgrows its 16-bit offsets")
    with open(dst, "w") as f:
        f.write("/* generated by tools/gen_voice.py from %s: do not edit */\n#pragma once\n" % src)
        f.write("#define VO_NDICT %du\n" % len(words))
        f.write("static const uint16_t VO_DOFF[VO_NDICT + 1] = {%s};\n" % ", ".join(map(str, offs)))
        f.write("static const uint8_t VO_DICT[%d] = {%s};\n" % (len(blob), ", ".join(map(str, blob))))
    print(f"voice: {len(words)} words, {len(blob) + 2 * len(offs)} B")


if __name__ == "__main__":
    main(*sys.argv[1:3])
